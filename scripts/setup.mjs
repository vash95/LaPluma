import { createInterface } from 'node:readline/promises';
import { mkdir, writeFile } from 'node:fs/promises';
import { randomBytes, scryptSync } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const rl = createInterface({input:process.stdin,output:process.stdout});
const email = (await rl.question('Email del administrador: ')).trim();
console.log('Introduce una contraseña de al menos 12 caracteres (se ocultará).');
rl.close();
if (!process.stdin.isTTY) throw new Error('Ejecuta la configuración en una terminal interactiva');
process.stdout.write('Contraseña: ');
process.stdin.setRawMode(true); process.stdin.resume();
let password = '';
await new Promise(resolve => process.stdin.on('data', chunk => { for (const char of chunk.toString()) { if (char === '\u0003') process.exit(1); if (char === '\r' || char === '\n') { process.stdin.setRawMode(false); process.stdin.pause(); resolve(); return; } if (char === '\u007f') password = password.slice(0,-1); else password += char; } }));
if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email) || password.length < 12 || password.length > 200) throw new Error('Email incorrecto o contraseña fuera de 12–200 caracteres');
const dir = process.env.DATA_DIR || fileURLToPath(new URL('../data/',import.meta.url));
await mkdir(dir,{recursive:true});
const salt = randomBytes(32).toString('hex');
await writeFile(path.join(dir,'account.json'),JSON.stringify({email,salt,hash:scryptSync(password,salt,64).toString('hex')}),{mode:0o600});
console.log('\nCuenta configurada. Inicia o reinicia el servidor con npm start.');
process.exit(0);
